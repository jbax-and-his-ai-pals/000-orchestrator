"""Evidence packs for bottleneck issues: a cheap, model-free primer for the agent that solves each issue.

For every open issue (triage/investigating), read the project's DOSSIER.md and pull the code the *blocker* cites
(files, line ranges, functions; found wherever they are defined) into `dossiers/<repo>/EVIDENCE.md`, plus recent
commits and the smoke result. The solver reads this first instead of re-exploring the repo, which saves frontier
quota. Read-only on the producer's checkouts.

    .venv/Scripts/python.exe briefs/evidence_packs.py [repo ...]     # default: every repo with an open issue
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ORCH = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ORCH / "scripts"))
import orch  # noqa: E402

EXT = r"(?:gd|py|cs|c|h|s|asm|inc|js|ts|lua|tscn|cfg|json|toml|ink|bat|ps1|sh|md|txt)"
FILE_RE = re.compile(r"(?<![\w/.-])((?:[\w.-]+/)*[\w.-]+\." + EXT + r")(?::(\d+)(?:-(\d+))?)?\b")
CALL_RE = re.compile(r"([A-Za-z_]\w*)\(\)")
TICK_RE = re.compile(r"`([A-Za-z_]\w*)(?:\(\))?`")
SRC_EXT = (".gd", ".py", ".cs", ".c", ".h", ".s", ".asm", ".inc", ".js", ".ts", ".lua")
MAX_LINES = 280            # code lines per pack
PER_EXCERPT = 45           # lines per excerpt
SKIP_DIRS = {".git", ".godot", ".import", "node_modules", "__pycache__", ".venv", "build", "bin", "obj"}


def section(text, heading):
    m = re.search(r"^" + re.escape(heading) + r"\s*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    return m.group(1).strip() if m else ""


def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8", errors="replace").splitlines()


def find_file(root: Path, rel: str) -> Path | None:
    p = root / rel
    if p.is_file():
        return p
    for q in root.rglob(Path(rel).name):
        if q.is_file() and not (set(q.relative_to(root).parts) & SKIP_DIRS):
            return q
    return None


def func_range(path: Path, name: str) -> tuple[int, int] | None:
    lines = read_lines(path)
    pat = re.compile(r"^\s*(?:static\s+)?(?:func|def|function|[\w*]+)\s+\*?" + re.escape(name) + r"\s*\(")
    for i, line in enumerate(lines):
        if pat.search(line):
            indent = len(line) - len(line.lstrip())
            j = i + 1
            while j < len(lines) and j - i < PER_EXCERPT:
                s = lines[j]
                if s.strip() and (len(s) - len(s.lstrip())) <= indent and not s.lstrip().startswith(("}", "#", "//", "{")):
                    break
                j += 1
            return i + 1, j
    return None


def cites_in(text):
    out = []
    for m in FILE_RE.finditer(text):
        rel, a, b = m.group(1), m.group(2), m.group(3)
        if rel.lower() != "dossier.md":
            out.append((rel, int(a) if a else None, int(b) if b else (int(a) if a else None)))
    return out


def funcs_in(text):
    names = CALL_RE.findall(text) + [n for n in TICK_RE.findall(text) if "_" in n]
    return [n for n in dict.fromkeys(names) if len(n) > 3 and not FILE_RE.fullmatch(n)]


def define_site(local: Path, files: list[Path], name: str):
    for f in files:
        if f.suffix in SRC_EXT and (r := func_range(f, name)):
            return f, r
    try:  # not in a cited file: look across the repo's tracked source
        hits = subprocess.run(["git", "-C", str(local), "grep", "-l", "-w", name],
                              capture_output=True, text=True, timeout=20).stdout.splitlines()
    except Exception:
        hits = []
    for rel in hits:
        f = local / rel
        if f.suffix in SRC_EXT and (r := func_range(f, name)):
            return f, r
    return None


def pack(repo: str, issue: dict, local: Path) -> str:
    text = (orch.DOSSIERS / repo / "DOSSIER.md").read_text(encoding="utf-8", errors="replace")
    blocker = re.search(r"\*\*Biggest blocker:\*\*(.*)", text)
    milestone = section(text, "## Next milestone")
    primary = "\n".join([issue["title"], blocker.group(1) if blocker else "",
                         *[l for l in milestone.splitlines() if re.search(r"\[(codex|claude)\]", l)]])
    secondary = "\n".join([section(text, "## Current state"), section(text, "## Bottlenecks")])
    out = [f"# Evidence pack: {repo}, issue {issue['id']}", "",
           "_Generated by briefs/evidence_packs.py from DOSSIER.md citations, blocker first. Model-free and read-only;",
           "excerpts may be partial._", "", f"**Issue:** {issue['title']}", ""]
    if blocker:
        out += [f"**Biggest blocker (dossier):** {blocker.group(1).strip()}", ""]
    if issue.get("note"):
        out += [f"**Previous attempt / rejection note:** {issue['note']}", ""]
    state = {"budget": MAX_LINES, "shown": set(), "files": set()}

    def emit(path, rng, why):
        key = (path, rng)
        if key in state["shown"] or state["budget"] <= 0:
            return
        state["shown"].add(key)
        state["files"].add(path)
        lines = read_lines(path)
        a, b = max(1, rng[0]), min(len(lines), rng[1])
        body = [f"{n:5d}  {lines[n - 1]}" for n in range(a, b + 1)][:min(PER_EXCERPT, state["budget"])]
        state["budget"] -= len(body)
        out.extend([f"## {path.relative_to(local).as_posix()}:{a}-{a + len(body) - 1} ({len(lines)} lines) · {why}",
                    "```", *body, "```", ""])

    pcites = cites_in(primary)
    pfiles = [find_file(local, rel) for rel, _, _ in pcites]
    for (rel, a, b), path in zip(pcites, pfiles):
        if path and a:
            emit(path, (a - 3, (b or a) + 3), "cited lines")
    missing = []
    for name in funcs_in(primary):
        site = define_site(local, [p for p in pfiles if p], name)
        if site:
            emit(site[0], site[1], f"`{name}`")
        else:
            missing.append(name)
    for path in pfiles:
        if path and path not in state["files"] and len(read_lines(path)) <= 60:
            emit(path, (1, 60), "whole file (short)")
    for rel, a, b in cites_in(secondary):  # background: exact line citations only, if room
        path = find_file(local, rel)
        if path and a and state["budget"] > 80:
            emit(path, (a - 2, (b or a) + 2), "cited in Current state/Bottlenecks")
    also = sorted({rel for rel, _, _ in pcites + cites_in(secondary)
                   if (p := find_file(local, rel)) and p not in state["files"]})
    if also:
        out += ["## Also cited (not excerpted)", ", ".join(also), ""]
    if missing:
        out += ["## Named but not located", ", ".join(f"`{f}`" for f in missing), ""]
    try:
        log = subprocess.run(["git", "-C", str(local), "log", "-5", "--format=%h %ad %s", "--date=short"],
                             capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        log = ""
    out += ["## Recent commits", "```", log or "(no git history)", "```", ""]
    smoke = orch.DOSSIERS / repo / "SMOKE.json"
    if smoke.exists():
        s = json.loads(smoke.read_text(encoding="utf-8"))
        out += ["## Smoke (orchestrator; Godot passes can be false greens)",
                f"- command: `{s.get('command')}` · ran: {s.get('ran')} · passed: {s.get('passed')}", ""]
    return "\n".join(out).rstrip() + "\n", len(state["shown"])


def main(argv):
    issues = [i for i in orch.list_issues() if i["status"] in ("triage", "investigating")]
    with orch.db() as con:
        paths = {r["repo_name"]: Path(r["local_path"]) for r in orch.rows(con, "SELECT repo_name, local_path FROM projects")}
    report = {}
    for i in issues:
        repo = i["project_name"]
        if argv and repo not in argv:
            continue
        if not (orch.DOSSIERS / repo / "DOSSIER.md").exists() or not paths.get(repo, Path("-")).exists():
            report[repo] = "skipped: no dossier or checkout"
            continue
        text, n = pack(repo, i, paths[repo])
        (orch.DOSSIERS / repo / "EVIDENCE.md").write_text(text, encoding="utf-8")
        report[repo] = f"{text.count(chr(10))} lines, {n} code excerpts"
    print(json.dumps(report, indent=1))


if __name__ == "__main__":
    main(sys.argv[1:])
